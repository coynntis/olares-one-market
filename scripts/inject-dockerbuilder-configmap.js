/**
 * Inline dockerbuilderone/app/* into templates/configmap.yaml.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const REPO = path.resolve(__dirname, '..');
const CHART = path.join(REPO, 'dockerbuilderone');
const APP_DIR = path.join(CHART, 'app');
const OUT = path.join(CHART, 'templates', 'configmap.yaml');


const FILE_KEYS = [
  'main.py',
  'builder.py',
  'deps.py',
  'mcp_server.py',
  'requirements.txt',
];

const STATIC_KEYS = [
  'static/index.html',
  'static/styles.css',
  'static/app.js',
];

function indentBlock(text, indent = 4) {
  const pad = ' '.repeat(indent);
  const lines = text.replace(/\r\n/g, '\n').split('\n');
  return lines.map((line) => pad + line).join('\n');
}

/** ConfigMap keys cannot contain '/'; map static/foo → static__foo */
function configKey(relPath) {
  return relPath.replace(/\//g, '__');
}

function injectDockerbuilderConfigmap() {
  for (const name of FILE_KEYS) {
    const p = path.join(APP_DIR, name);
    if (!fs.existsSync(p)) {
      console.warn('[inject-dockerbuilder-configmap] skip: missing', p);
      return false;
    }
  }
  for (const name of STATIC_KEYS) {
    const p = path.join(APP_DIR, name);
    if (!fs.existsSync(p)) {
      console.warn('[inject-dockerbuilder-configmap] skip: missing', p);
      return false;
    }
  }

  const dataBlocks = [];

  for (const name of FILE_KEYS) {
    const text = fs.readFileSync(path.join(APP_DIR, name), 'utf8');
    dataBlocks.push([`  ${name}: |`, indentBlock(text)].join('\n'));
  }

  for (const rel of STATIC_KEYS) {
    const text = fs.readFileSync(path.join(APP_DIR, rel), 'utf8');
    const key = configKey(rel);
    dataBlocks.push([`  ${key}: |`, indentBlock(text)].join('\n'));
  }

  const body = [
    '---',
    '# Generated by scripts/inject-dockerbuilder-configmap.js — edit dockerbuilderone/app/ then npm run build:catalog',
    'apiVersion: v1',
    'kind: ConfigMap',
    'metadata:',
    '  name: dockerbuilderone-source',
    '  namespace: "{{ .Release.Namespace }}"',
    'data:',
    ...dataBlocks,
    '',
  ].join('\n');

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (prev !== body) {
    fs.writeFileSync(OUT, body);
    console.log('[inject-dockerbuilder-configmap] wrote', path.relative(REPO, OUT));
  } else {
    console.log('[inject-dockerbuilder-configmap] unchanged', path.relative(REPO, OUT));
  }
  return true;
}

if (require.main === module) {
  injectDockerbuilderConfigmap();
}

module.exports = { injectDockerbuilderConfigmap };
