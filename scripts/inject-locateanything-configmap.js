/**
 * Inline locateanything3bone/files/* into templates/configmap.yaml.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const REPO = path.resolve(__dirname, '..');
const CHART = path.join(REPO, 'locateanything3bone');
const FILES_DIR = path.join(CHART, 'files');
const OUT = path.join(CHART, 'templates', 'configmap.yaml');

const FILE_KEYS = [
  'app.py',
  'worker.py',
  'requirements.txt',
  'bootstrap_deps.sh',
  'install_magiattention.sh',
  'magi_build_requirements.txt',
];

function indentBlock(text, indent = 4) {
  const pad = ' '.repeat(indent);
  const lines = text.replace(/\r\n/g, '\n').split('\n');
  return lines.map((line) => pad + line).join('\n');
}

function injectLocateanythingConfigmap() {
  for (const name of FILE_KEYS) {
    const p = path.join(FILES_DIR, name);
    if (!fs.existsSync(p)) {
      console.warn('[inject-locateanything-configmap] skip: missing', p);
      return false;
    }
  }

  const dataBlocks = FILE_KEYS.map((name) => {
    const text = fs.readFileSync(path.join(FILES_DIR, name), 'utf8');
    return [`  ${name}: |`, indentBlock(text)].join('\n');
  });

  const body = [
    '---',
    '# Generated by scripts/inject-locateanything-configmap.js — edit locateanything3bone/files/ then npm run build:catalog',
    'apiVersion: v1',
    'kind: ConfigMap',
    'metadata:',
    '  name: locateanything3bone-source',
    '  namespace: "{{ .Release.Namespace }}"',
    'data:',
    ...dataBlocks,
    '',
  ].join('\n');

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (prev !== body) {
    fs.writeFileSync(OUT, body);
    console.log('[inject-locateanything-configmap] wrote', path.relative(REPO, OUT));
  } else {
    console.log('[inject-locateanything-configmap] unchanged', path.relative(REPO, OUT));
  }
  return true;
}

if (require.main === module) {
  injectLocateanythingConfigmap();
}

module.exports = { injectLocateanythingConfigmap };
