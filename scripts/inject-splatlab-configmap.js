function indentBlock(text, indent = 4) {
  const pad = ' '.repeat(indent);
  const lines = text.replace(/\r\n/g, '\n').split('\n');
  return lines.map((line) => pad + line).join('\n');
}

function configKey(relPath) {
  return relPath.replace(/\//g, '--');
}

function injectSplatlabConfigmap() {
  const allKeys = [...FILE_KEYS, ...STATIC_KEYS, ...PRESET_KEYS];
  for (const name of allKeys) {
    const p = path.join(APP_DIR, name);
    if (!fs.existsSync(p)) {
      console.warn('[inject-splatlab-configmap] skip: missing', p);
      return false;
    }
  }

  const dataBlocks = [];
  for (const name of FILE_KEYS) {
    const text = fs.readFileSync(path.join(APP_DIR, name), 'utf8');
    dataBlocks.push([`  ${configKey(name)}: |`, indentBlock(text)].join('\n'));
  }
  for (const rel of STATIC_KEYS) {
    const text = fs.readFileSync(path.join(APP_DIR, rel), 'utf8');
    dataBlocks.push([`  ${configKey(rel)}: |`, indentBlock(text)].join('\n'));
  }
  for (const rel of PRESET_KEYS) {
    const text = fs.readFileSync(path.join(APP_DIR, rel), 'utf8');
    dataBlocks.push([`  ${configKey(rel)}: |`, indentBlock(text)].join('\n'));
  }
  for (const { rel, key } of EXTRA_FILES) {
    const p = path.join(CHART, rel);
    if (!fs.existsSync(p)) {
      console.warn('[inject-splatlab-configmap] skip extra: missing', p);
      return false;
    }
    const text = fs.readFileSync(p, 'utf8');
    dataBlocks.push([`  ${key}: |`, indentBlock(text)].join('\n'));
  }

  const body = [
    '---',
    '# Generated by scripts/inject-splatlab-configmap.js — edit splatlabone/app/ then npm run build:catalog',
    'apiVersion: v1',
    'kind: ConfigMap',
    'metadata:',
    '  name: splatlabone-source',
    '  namespace: "{{ .Release.Namespace }}"',
    'data:',
    ...dataBlocks,
    '',
  ].join('\n');

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (prev !== body) {
    fs.writeFileSync(OUT, body);
    console.log('[inject-splatlab-configmap] wrote', path.relative(REPO, OUT));
  } else {
    console.log('[inject-splatlab-configmap] unchanged', path.relative(REPO, OUT));
  }
  return true;
}

if (require.main === module) {
  injectSplatlabConfigmap();
}

module.exports = { injectSplatlabConfigmap };
