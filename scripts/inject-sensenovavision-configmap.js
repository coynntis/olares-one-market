/**
 * Inline sensenovavisionone/app/* into templates/configmap.yaml.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const REPO = path.resolve(__dirname, '..');
const APP = 'sensenovavisionone';
const CHART = path.join(REPO, APP);
const APP_DIR = path.join(CHART, 'app');
const OUT = path.join(CHART, 'templates', 'configmap.yaml');

const FILES = [
  'app.py',
  'soft_ready.py',
  'download_models.py',
  '_common.py',
  'requirements.txt',
  'patch_flash_sdpa.py',
];

/** Escape literal brace-pairs so Helm does not parse Python/CSS/JS as templates. */
function escapeHelmLiterals(text) {
  return text
    .replace(/\{\{/g, '\u0000HELM_OPEN\u0000')
    .replace(/\}\}/g, '\u0000HELM_CLOSE\u0000')
    .replace(/\u0000HELM_OPEN\u0000/g, '{{ "{{" }}')
    .replace(/\u0000HELM_CLOSE\u0000/g, '{{ "}}" }}');
}

function indentBlock(text, indent = 4) {
  const pad = ' '.repeat(indent);
  return escapeHelmLiterals(text)
    .replace(/\r\n/g, '\n')
    .split('\n')
    .map((line) => pad + line)
    .join('\n');
}

function injectSensenovavisionConfigmap() {
  for (const f of FILES) {
    if (!fs.existsSync(path.join(APP_DIR, f))) {
      console.warn(`[inject-sensenovavision] skip: missing app/${f}`);
      return false;
    }
  }
  const body = [
    '---',
    `# Generated by scripts/inject-sensenovavision-configmap.js — edit ${APP}/app/ then npm run build`,
    'apiVersion: v1',
    'kind: ConfigMap',
    'metadata:',
    `  name: ${APP}-source`,
    '  namespace: "{{ .Release.Namespace }}"',
    'data:',
  ];
  for (const f of FILES) {
    body.push(`  ${f}: |`);
    body.push(indentBlock(fs.readFileSync(path.join(APP_DIR, f), 'utf8')));
  }
  body.push('');
  const text = body.join('\n');
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (prev !== text) {
    fs.writeFileSync(OUT, text);
    console.log('[inject-sensenovavision] wrote', path.relative(REPO, OUT));
  } else {
    console.log('[inject-sensenovavision] unchanged', path.relative(REPO, OUT));
  }
  return true;
}

module.exports = { injectSensenovavisionConfigmap };

if (require.main === module) {
  injectSensenovavisionConfigmap();
}
