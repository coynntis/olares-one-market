/**
 * Inline sensenovau1infov2one/files/*.py and requirements.txt into templates/configmap.yaml.
 * Source of truth: sensenovau1infov2one/files/
 * Generated: sensenovau1infov2one/templates/configmap.yaml
 */
'use strict';

const fs = require('fs');
const path = require('path');

const REPO = path.resolve(__dirname, '..');
const CHART = path.join(REPO, 'sensenovau1infov2one');
const FILES_DIR = path.join(CHART, 'files');
const OUT = path.join(CHART, 'templates', 'configmap.yaml');

function indentBlock(text, indent = 4) {
  const pad = ' '.repeat(indent);
  const lines = text.replace(/\r\n/g, '\n').split('\n');
  return lines.map((line) => pad + line).join('\n');
}

function injectSensenovaInfov2Configmap() {
  const appPath = path.join(FILES_DIR, 'app.py');
  const reqPath = path.join(FILES_DIR, 'requirements.txt');
  const flashPath = path.join(FILES_DIR, 'install_flash_attn.py');

  if (!fs.existsSync(appPath) || !fs.existsSync(reqPath) || !fs.existsSync(flashPath)) {
    console.warn('[inject-sensenovau1infov2-configmap] skip: missing sources');
    return false;
  }

  const appPy = fs.readFileSync(appPath, 'utf8');
  const requirements = fs.readFileSync(reqPath, 'utf8');
  const installFlash = fs.readFileSync(flashPath, 'utf8');

  const body = [
    '---',
    '# Generated by scripts/inject-sensenovau1infov2-configmap.js — edit sensenovau1infov2one/files/ then npm run build',
    'apiVersion: v1',
    'kind: ConfigMap',
    'metadata:',
    '  name: sensenovau1infov2one-source',
    '  namespace: "{{ .Release.Namespace }}"',
    'data:',
    '  app.py: |',
    indentBlock(appPy),
    '  install_flash_attn.py: |',
    indentBlock(installFlash),
    '  requirements.txt: |',
    indentBlock(requirements),
    '',
  ].join('\n');

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (prev !== body) {
    fs.writeFileSync(OUT, body);
    console.log('[inject-sensenovau1infov2-configmap] wrote', path.relative(REPO, OUT));
  } else {
    console.log('[inject-sensenovau1infov2-configmap] unchanged', path.relative(REPO, OUT));
  }
  return true;
}

if (require.main === module) {
  injectSensenovaInfov2Configmap();
}

module.exports = { injectSensenovaInfov2Configmap };
