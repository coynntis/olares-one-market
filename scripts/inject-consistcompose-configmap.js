/**
 * Inline consistcomposeone/files/* into templates/configmap.yaml.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const REPO = path.resolve(__dirname, '..');
const CHART = path.join(REPO, 'consistcomposeone');
const FILES_DIR = path.join(CHART, 'files');
const OUT = path.join(CHART, 'templates', 'configmap.yaml');

function indentBlock(text, indent = 4) {
  const pad = ' '.repeat(indent);
  const lines = text.replace(/\r\n/g, '\n').split('\n');
  return lines.map((line) => pad + line).join('\n');
}

function injectConsistcomposeConfigmap() {
  const appPath = path.join(FILES_DIR, 'app.py');
  const reqPath = path.join(FILES_DIR, 'requirements.txt');
  const patchPath = path.join(FILES_DIR, 'patch_flash_sdpa.py');

  if (!fs.existsSync(appPath) || !fs.existsSync(reqPath) || !fs.existsSync(patchPath)) {
    console.warn('[inject-consistcompose-configmap] skip: missing files/ sources');
    return false;
  }

  const appPy = fs.readFileSync(appPath, 'utf8');
  const requirements = fs.readFileSync(reqPath, 'utf8');
  const patchPy = fs.readFileSync(patchPath, 'utf8');

  const body = [
    '---',
    '# Generated by scripts/inject-consistcompose-configmap.js — edit consistcomposeone/files/ then npm run build:catalog',
    'apiVersion: v1',
    'kind: ConfigMap',
    'metadata:',
    '  name: consistcomposeone-source',
    '  namespace: "{{ .Release.Namespace }}"',
    'data:',
    '  app.py: |',
    indentBlock(appPy),
    '  requirements.txt: |',
    indentBlock(requirements),
    '  patch_flash_sdpa.py: |',
    indentBlock(patchPy),
    '',
  ].join('\n');

  fs.writeFileSync(OUT, body, 'utf8');
  console.log('[inject-consistcompose-configmap] wrote', OUT);
  return true;
}

if (require.main === module) {
  injectConsistcomposeConfigmap();
}

module.exports = { injectConsistcomposeConfigmap };
