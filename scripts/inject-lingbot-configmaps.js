/**
 * Inline each lingbot chart app/ sources into templates/configmap.yaml.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const REPO = path.resolve(__dirname, '..');

const APPS = [
  'lingbotdepthone',
  'lingbotvisionone',
  'lingbotmapone',
  'lingbotvideoone',
  'lingbotvlaone',
  'lingbotvaone',
  'lingbotworldone',
];

const FILES = ['app.py', 'soft_ready.py', 'download_models.py', '_common.py', 'requirements.txt'];

/** Optional extra app/ files per chart (e.g. map measure tools). */
const EXTRA_FILES = {
  lingbotmapone: ['measure_tools.py'],
};

/** Escape literal brace-pairs so Helm does not parse Python/CSS/JS as templates. */
function escapeHelmLiterals(text) {
  // Two-phase replace so closing braces in the open-escape do not get re-escaped.
  return text
    .replace(/\{\{/g, '\u0000HELM_OPEN\u0000')
    .replace(/\}\}/g, '\u0000HELM_CLOSE\u0000')
    .replace(/\u0000HELM_OPEN\u0000/g, '{{ "{{" }}')
    .replace(/\u0000HELM_CLOSE\u0000/g, '{{ "}}" }}');
}

function indentBlock(text, indent = 4) {
  const pad = ' '.repeat(indent);
  return escapeHelmLiterals(text)
    .replace(/\r\n/g, '\n')
    .split('\n')
    .map((line) => pad + line)
    .join('\n');
}

function injectOne(appName) {
  const chart = path.join(REPO, appName);
  const appDir = path.join(chart, 'app');
  const out = path.join(chart, 'templates', 'configmap.yaml');
  const files = FILES.concat(EXTRA_FILES[appName] || []);
  for (const f of files) {
    if (!fs.existsSync(path.join(appDir, f))) {
      console.warn(`[inject-lingbot] skip ${appName}: missing app/${f}`);
      return false;
    }
  }
  const body = [
    '---',
    `# Generated by scripts/inject-lingbot-configmaps.js — edit ${appName}/app/ then npm run build`,
    'apiVersion: v1',
    'kind: ConfigMap',
    'metadata:',
    `  name: ${appName}-source`,
    '  namespace: "{{ .Release.Namespace }}"',
    'data:',
  ];
  for (const f of files) {
    body.push(`  ${f}: |`);
    body.push(indentBlock(fs.readFileSync(path.join(appDir, f), 'utf8')));
  }
  body.push('');
  const text = body.join('\n');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  const prev = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (prev !== text) {
    fs.writeFileSync(out, text);
    console.log('[inject-lingbot] wrote', path.relative(REPO, out));
  } else {
    console.log('[inject-lingbot] unchanged', path.relative(REPO, out));
  }
  return true;
}

function injectLingbotConfigmaps() {
  let n = 0;
  for (const app of APPS) {
    if (injectOne(app)) n += 1;
  }
  return n;
}

module.exports = { injectLingbotConfigmaps, APPS };

if (require.main === module) {
  injectLingbotConfigmaps();
}
