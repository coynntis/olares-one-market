/**
 * Inline mageflowone/app/* into templates/configmap.yaml.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const REPO = path.resolve(__dirname, '..');
const CHART = path.join(REPO, 'mageflowone');
const APP_DIR = path.join(CHART, 'app');
const OUT = path.join(CHART, 'templates', 'configmap.yaml');

function indentBlock(text, indent = 4) {
  const pad = ' '.repeat(indent);
  return text.replace(/\r\n/g, '\n').split('\n').map((line) => pad + line).join('\n');
}

function injectMageflowConfigmap() {
  const appPath = path.join(APP_DIR, 'app.py');
  const reqPath = path.join(APP_DIR, 'requirements.txt');
  const softPath = path.join(APP_DIR, 'soft_ready.py');
  const mcpPath = path.join(APP_DIR, 'mcp_server.py');
  if (!fs.existsSync(appPath) || !fs.existsSync(reqPath) || !fs.existsSync(softPath) || !fs.existsSync(mcpPath)) {
    console.warn('[inject-mageflow-configmap] skip: missing app sources');
    return false;
  }

  const body = [
    '---',
    '# Generated by scripts/inject-mageflow-configmap.js — edit mageflowone/app/ then npm run build',
    'apiVersion: v1',
    'kind: ConfigMap',
    'metadata:',
    '  name: mageflowone-source',
    '  namespace: "{{ .Release.Namespace }}"',
    'data:',
    '  app.py: |',
    indentBlock(fs.readFileSync(appPath, 'utf8')),
    '  mcp_server.py: |',
    indentBlock(fs.readFileSync(mcpPath, 'utf8')),
    '  soft_ready.py: |',
    indentBlock(fs.readFileSync(softPath, 'utf8')),
    '  requirements.txt: |',
    indentBlock(fs.readFileSync(reqPath, 'utf8')),
    '',
  ].join('\n');

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (prev !== body) {
    fs.writeFileSync(OUT, body);
    console.log('[inject-mageflow-configmap] wrote', path.relative(REPO, OUT));
  } else {
    console.log('[inject-mageflow-configmap] unchanged', path.relative(REPO, OUT));
  }
  return true;
}

module.exports = { injectMageflowConfigmap };

if (require.main === module) {
  injectMageflowConfigmap();
}
