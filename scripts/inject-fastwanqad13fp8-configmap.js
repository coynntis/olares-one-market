/**
 * Inline fastwanqad13fp8one/app/* into templates/configmap.yaml.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const REPO = path.resolve(__dirname, '..');
const CHART = path.join(REPO, 'fastwanqad13fp8one');
const APP_DIR = path.join(CHART, 'app');
const OUT = path.join(CHART, 'templates', 'configmap.yaml');

const FILE_KEYS = ['app.py', 'fastwan_worker_patch.py', 'requirements.txt'];

function indentBlock(text, indent = 4) {
  const pad = ' '.repeat(indent);
  return text.replace(/\r\n/g, '\n').split('\n').map((line) => pad + line).join('\n');
}

function injectFastwanqad13fp8Configmap() {
  for (const name of FILE_KEYS) {
    if (!fs.existsSync(path.join(APP_DIR, name))) {
      console.warn('[inject-fastwanqad13fp8-configmap] skip: missing', name);
      return false;
    }
  }

  const dataBlocks = FILE_KEYS.map((name) => {
    const text = fs.readFileSync(path.join(APP_DIR, name), 'utf8');
    return [`  ${name}: |`, indentBlock(text)].join('\n');
  });

  const body = [
    '---',
    '# Generated by scripts/inject-fastwanqad13fp8-configmap.js — edit fastwanqad13fp8one/app/ then npm run build:catalog',
    'apiVersion: v1',
    'kind: ConfigMap',
    'metadata:',
    '  name: fastwanqad13fp8one-source',
    '  namespace: "{{ .Release.Namespace }}"',
    'data:',
    ...dataBlocks,
    '',
  ].join('\n');

  const full = body;

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (prev !== full) {
    fs.writeFileSync(OUT, full);
    console.log('[inject-fastwanqad13fp8-configmap] wrote', path.relative(REPO, OUT));
  } else {
    console.log('[inject-fastwanqad13fp8-configmap] unchanged', path.relative(REPO, OUT));
  }
  return true;
}

module.exports = { injectFastwanqad13fp8Configmap };

if (require.main === module) {
  injectFastwanqad13fp8Configmap();
}
