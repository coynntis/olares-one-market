/**
 * Inline ideogram4nf4one/app/* into templates/configmap.yaml.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const REPO = path.resolve(__dirname, '..');
const CHART = path.join(REPO, 'ideogram4nf4one');
const APP_DIR = path.join(CHART, 'app');
const OUT = path.join(CHART, 'templates', 'configmap.yaml');

function indentBlock(text, indent = 4) {
  const pad = ' '.repeat(indent);
  const lines = text.replace(/\r\n/g, '\n').split('\n');
  return lines.map((line) => pad + line).join('\n');
}

function injectIdeogram4Configmap() {
  const appPath = path.join(APP_DIR, 'app.py');
  const reqPath = path.join(APP_DIR, 'requirements.txt');

  if (!fs.existsSync(appPath) || !fs.existsSync(reqPath)) {
    console.warn('[inject-ideogram4-configmap] skip: missing app sources');
    return false;
  }

  const appPy = fs.readFileSync(appPath, 'utf8');
  const requirements = fs.readFileSync(reqPath, 'utf8');

  const body = [
    '---',
    '# Generated by scripts/inject-ideogram4-configmap.js — edit ideogram4nf4one/app/ then npm run build:catalog',
    'apiVersion: v1',
    'kind: ConfigMap',
    'metadata:',
    '  name: ideogram4nf4one-source',
    '  namespace: "{{ .Release.Namespace }}"',
    'data:',
    '  app.py: |',
    indentBlock(appPy),
    '  requirements.txt: |',
    indentBlock(requirements),
    '',
  ].join('\n');

  fs.writeFileSync(OUT, body, 'utf8');
  console.log('[inject-ideogram4-configmap] wrote', OUT);
  return true;
}

if (require.main === module) {
  injectIdeogram4Configmap();
}

module.exports = { injectIdeogram4Configmap };
