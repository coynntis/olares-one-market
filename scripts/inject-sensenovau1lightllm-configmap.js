/**
 * Inline sensenovau1lightllmone/files/benchmark_t2i.py into templates/configmap.yaml.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const REPO = path.resolve(__dirname, '..');
const CHART = path.join(REPO, 'sensenovau1lightllmone');
const SRC = path.join(CHART, 'files', 'benchmark_t2i.py');
const OUT = path.join(CHART, 'templates', 'configmap.yaml');

function indentBlock(text, indent = 4) {
  const pad = ' '.repeat(indent);
  return text.replace(/\r\n/g, '\n').split('\n').map((line) => pad + line).join('\n');
}

function injectSensenovau1LightllmConfigmap() {
  if (!fs.existsSync(SRC)) {
    console.warn('[inject-sensenovau1lightllm-configmap] skip: missing', SRC);
    return false;
  }

  const body = [
    '---',
    '# Generated by scripts/inject-sensenovau1lightllm-configmap.js — edit files/benchmark_t2i.py then npm run build',
    'apiVersion: v1',
    'kind: ConfigMap',
    'metadata:',
    '  name: sensenovau1lightllmone-bench',
    '  namespace: "{{ .Release.Namespace }}"',
    'data:',
    '  benchmark_t2i.py: |',
    indentBlock(fs.readFileSync(SRC, 'utf8')),
    '',
  ].join('\n');

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (prev !== body) {
    fs.writeFileSync(OUT, body);
    console.log('[inject-sensenovau1lightllm-configmap] wrote', path.relative(REPO, OUT));
  } else {
    console.log('[inject-sensenovau1lightllm-configmap] unchanged', path.relative(REPO, OUT));
  }
  return true;
}

module.exports = { injectSensenovau1LightllmConfigmap };

if (require.main === module) {
  injectSensenovau1LightllmConfigmap();
}
